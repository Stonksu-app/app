export function getNodeById(id: string): SkillNode | undefined {
  return SKILL_TREE.find((n) => n.id === id);
}

export function getLessonById(lessonId: string): { node: SkillNode; lesson: SkillNode['lessons'][number] } | undefined {
  for (const node of SKILL_TREE) {
    const lesson = node.lessons.find((l) => l.id === lessonId);
    if (lesson) return { node, lesson };
  }
  return undefined;
}
