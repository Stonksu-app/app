export interface Section {
  number: number;
  title: string;
  /** In path order, which is also unlock order. */
  units: SkillNode[];
}

/**
 * The tree grouped into sections, in the order the path walks them.
 *
 * Derived rather than stored: the section a topic belongs to already lives on
 * the topic, and a second list would be one more thing to keep in step.
 */
export function getSections(): Section[] {
  const byNumber = new Map<number, Section>();
  for (const node of SKILL_TREE) {
    if (!node.section) continue;
    const existing = byNumber.get(node.section.number);
    if (existing) existing.units.push(node);
    else byNumber.set(node.section.number, { ...node.section, units: [node] });
  }
  return [...byNumber.values()].sort((a, b) => a.number - b.number);
}

export function getNodeById(id: string): SkillNode | undefined {
  return SKILL_TREE.find((n) => n.id === id);
}

export function getLessonById(lessonId: string): { node: SkillNode; lesson: SkillNode['lessons'][number] } | undefined {
  for (const node of SKILL_TREE) {
    const lesson = node.lessons.find((l) => l.id === lessonId);
    if (lesson) return { node, lesson };
  }
  return undefined;
}

/**
 * Every question from an already-completed lesson, excluding the node
 * currently being played.
 *
 * Feeds the cross-lesson review question in buildStage: a topic covered
 * weeks ago and never revisited again is the one that actually gets
 * forgotten, so this pulls candidates from everywhere else in the tree
 * rather than only from the current node (which already gets its own
 * "Repaso" stage at the end).
 */
export function getReviewPool(completedLessonIds: string[], excludeNodeId: string): QuizQuestion[] {
  const pool: QuizQuestion[] = [];
  for (const node of SKILL_TREE) {
    if (node.id === excludeNodeId) continue;
    for (const lesson of node.lessons) {
      if (completedLessonIds.includes(lesson.id)) pool.push(...lesson.questions);
    }
  }
  return pool;
}
